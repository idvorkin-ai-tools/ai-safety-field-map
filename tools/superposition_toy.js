#!/usr/bin/env node
// Regenerates lab/superposition-data.js: the 20-feature, 5-dimension toy model of
// Elhage et al. 2022 (Toy Models of Superposition), x' = ReLU(W^T W x + b), trained once
// per sparsity level with importance 0.7^i. Deterministic (seeded). Run:
//   node tools/superposition_toy.js > lab/superposition-data.js
'use strict';
const N = 20, M = 5, BATCH = 1024, STEPS = +(process.env.STEPS || 12000), LR = 1e-3;
const SPARSITY = [0, 0.7, 0.9, 0.97, 0.99, 0.997, 0.999];
const IMP = Array.from({ length: N }, (_, i) => Math.pow(0.7, i));
function rng(seed) { let s = seed >>> 0; return () => { s = (s + 0x6D2B79F5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
function train(S, seed) {
  const r = rng(seed);
  const gauss = () => Math.sqrt(-2 * Math.log(r() + 1e-12)) * Math.cos(2 * Math.PI * r());
  const W = Array.from({ length: M * N }, () => gauss() * Math.sqrt(2 / (M + N)));
  const b = new Array(N).fill(0);
  const P = W.length + N, m1 = new Float64Array(P), m2 = new Float64Array(P);
  const x = new Float64Array(N), h = new Float64Array(M), gW = new Float64Array(M * N), gb = new Float64Array(N), d = new Float64Array(N);
  for (let step = 1; step <= STEPS; step++) {
    gW.fill(0); gb.fill(0);
    for (let k = 0; k < BATCH; k++) {
      let any = false;
      for (let i = 0; i < N; i++) { x[i] = r() < S ? 0 : r(); if (x[i]) any = true; }
      h.fill(0);
      if (any) for (let j = 0; j < M; j++) { let s = 0; for (let i = 0; i < N; i++) s += W[j * N + i] * x[i]; h[j] = s; }
      for (let i = 0; i < N; i++) {
        let o = b[i]; for (let j = 0; j < M; j++) o += W[j * N + i] * h[j];
        d[i] = o > 0 ? 2 * IMP[i] * (o - x[i]) / BATCH : 0;
        gb[i] += d[i];
      }
      // dL/dW[j,i] = d_i * h_j  +  x_i * sum_k d_k W[j,k]
      for (let j = 0; j < M; j++) {
        let s = 0; for (let kk = 0; kk < N; kk++) s += d[kk] * W[j * N + kk];
        for (let i = 0; i < N; i++) gW[j * N + i] += d[i] * h[j] + x[i] * s;
      }
    }
    const b1 = 0.9, b2 = 0.999, c1 = 1 - Math.pow(b1, step), c2 = 1 - Math.pow(b2, step);
    for (let p = 0; p < P; p++) {
      const g = p < W.length ? gW[p] : gb[p - W.length];
      m1[p] = b1 * m1[p] + (1 - b1) * g; m2[p] = b2 * m2[p] + (1 - b2) * g * g;
      const u = LR * (m1[p] / c1) / (Math.sqrt(m2[p] / c2) + 1e-8);
      if (p < W.length) W[p] -= u; else b[p - W.length] -= u;
    }
  }
  return { S, W: W.map(v => +v.toFixed(3)), b: b.map(v => +v.toFixed(3)) };
}
const runs = SPARSITY.map((S, k) => train(S, 1000 + k));
process.stdout.write('// Generated by tools/superposition_toy.js (' + STEPS + ' Adam steps per level, batch ' + BATCH + '). Do not edit by hand.\n' +
  '// W is 5x20 row-major: W[j*20+i] is feature i in hidden dimension j.\n' +
  '(function (root) {\n  var data = ' + JSON.stringify(runs) + ';\n' +
  "  if (typeof module === 'object' && module.exports) module.exports = data;\n  else (root.AISafetyLab = root.AISafetyLab || {}).superpositionRuns = data;\n})(this);\n");
