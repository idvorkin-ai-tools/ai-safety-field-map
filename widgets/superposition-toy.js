// interp/superposition.html#why-it-happens: step through precomputed toy runs.
// Data: lab/superposition-data.js (from tools/superposition_toy.js); maths: lab/superposition.js.
(function () {
  var H = window.AIToolsWidgets, A = window.AISafetyLab;
  if (!H || !A || !A.superposition || !A.superpositionRuns) return;
  var L = A.superposition, RUNS = A.superpositionRuns, C = 7.2, GX = 8, GY = 14, BX = 182, BW = 170;
  H.register('superposition-toy', function (el) {
    var p = 'sp' + H.uid();
    el.innerHTML = H.presets([['0', 'Dense'], ['2', 'Sparse: pairs'], ['6', 'Very sparse']]) +
      '<div class="lab-ctl">' + H.slider(p + '-s', 'Feature sparsity S (chance a feature is off on a given input)', 0, RUNS.length - 1, 1, 0) + '</div>' +
      '<svg viewBox="0 0 360 178" role="img" aria-labelledby="' + p + '-sum"><g id="' + p + '-g"></g></svg>' +
      '<div class="statgrid">' + H.stat('features stored', p + '-n') + H.stat('per dimension', p + '-k') + H.stat('opposite pairs', p + '-a') + '</div>' +
      H.sum(p + '-sum') + '<p class="lab-note">Precomputed: our own run of the toy setup from the paper and Technical AI Safety 4.1\'s exercise (20 features, 5 dimensions, geometrically falling importance; we chose 0.7<sup>i</sup>; one training seed per level), regenerated by tools/superposition_toy.js. It shows the qualitative change the page describes, not the paper\'s exact figure.</p>';
    var s = H.$(el, p + '-s');
    function draw() {
      var run = RUNS[+s.value], W = run.W, g = L.gram(W), n = L.norms(W), inf = L.interference(W), rep = L.represented(W), pairs = L.antipodalPairs(W);
      H.$(el, p + '-s-o').textContent = 'S = ' + run.S;
      var o = H.t(GX, 10, 'WᵀW, feature by feature', 'lab-ax');
      for (var i = 0; i < 20; i++) for (var k = 0; k < 20; k++) {
        var v = Math.max(-1, Math.min(1, g[i][k]));
        o += '<rect class="' + (v < 0 ? 'hm-neg' : 'hm-pos') + '" x="' + (GX + k * C).toFixed(1) + '" y="' + (GY + i * C).toFixed(1) + '" width="' + (C - 0.6) + '" height="' + (C - 0.6) + '" fill-opacity="' + Math.abs(v).toFixed(2) + '"/>';
      }
      o += H.t(BX, 10, 'how strongly each is stored', 'lab-ax');
      for (i = 0; i < 20; i++) {
        var w = Math.min(n[i], 1.2) / 1.2 * (BW - 24), yy = GY + i * C;
        o += '<rect class="lab-track" x="' + (BX + 20) + '" y="' + yy.toFixed(1) + '" width="' + (BW - 24) + '" height="' + (C - 1.4) + '"/>' +
          '<rect class="' + (n[i] <= 0.5 ? 'bar-weak' : inf[i] > 0.1 ? 'bar-sup' : 'bar-own') + '" x="' + (BX + 20) + '" y="' + yy.toFixed(1) + '" width="' + w.toFixed(1) + '" height="' + (C - 1.4) + '"/>';
        if (i % 5 === 0) o += H.t(BX + 16, yy + 6, i + 1, 'lab-ax', 'text-anchor="end"');
      }
      o += H.t(BX + 20, GY + 20 * C + 12, '■ alone', 'lab-ax lab-ax-def') + H.t(BX + 70, GY + 20 * C + 12, '■ shared', 'lab-ax lab-ax-off') + H.t(BX + 124, GY + 20 * C + 12, '■ faint', 'lab-ax');
      o += H.t(GX, GY + 20 * C + 12, 'cyan +, amber −', 'lab-ax');
      H.$(el, p + '-g').innerHTML = o;
      H.$(el, p + '-n').textContent = rep + ' of 20';
      H.$(el, p + '-k').textContent = H.f2(rep / 5);
      H.$(el, p + '-a').textContent = pairs;
      H.$(el, p + '-sum').textContent = 'At sparsity ' + run.S + ', the toy model stores ' + rep + ' of 20 features in 5 dimensions' +
        (rep <= 5 ? ', each in its own dimension with no overlap.' : ', so features share space' + (pairs ? ', ' + 2 * pairs + ' of them as ' + (pairs === 1 ? 'one pair' : pairs + ' pairs') + ' pointing in opposite directions.' : '.'));
    }
    function preset(k) { s.value = k; draw(); }
    el.labPreset = preset;
    el.querySelectorAll('.lab-pre [data-p]').forEach(function (b) { b.addEventListener('click', function () { preset(b.getAttribute('data-p')); }); });
    s.addEventListener('input', draw);
    draw();
  });
})();
